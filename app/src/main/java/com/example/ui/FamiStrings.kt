    fun localeFor(langCode: String): Locale {
        return when (langCode.lowercase()) {
            "en" -> Locale.US
            "pt" -> Locale("pt", "BR")
            "fr" -> Locale.FRANCE
            "it" -> Locale.ITALY
            "de" -> Locale.GERMANY
            "zh" -> Locale.SIMPLIFIED_CHINESE
            "ja" -> Locale.JAPAN
            "ko" -> Locale.KOREA
            "ar" -> Locale("ar", "SA")
            else -> Locale("es", "ES")
        }
    }

    fun speechLocaleFor(langCode: String): String {
        return when (langCode.lowercase()) {
            "en" -> "en-US"
            "pt" -> "pt-BR"
            "fr" -> "fr-FR"
            "it" -> "it-IT"
            "de" -> "de-DE"
            "zh" -> "zh-CN"
            "ja" -> "ja-JP"
            "ko" -> "ko-KR"
            "ar" -> "ar-SA"
            else -> "es-ES"
        }
    }

    fun monthName(monthIndex: Int, langCode: String): String {
        val loc = localeFor(langCode)
        val raw = runCatching { DateFormatSymbols.getInstance(loc).months.getOrNull(monthIndex) }.getOrNull().orEmpty()
        return raw.replaceFirstChar { it.titlecase(loc) }.ifBlank { (monthIndex + 1).toString() }
    }

    fun weekDayHeaders(langCode: String): List<String> {
        return when (langCode.lowercase()) {
            "en" -> listOf("Mo", "Tu", "We", "Th", "Fr", "Sa", "Su")
            "pt" -> listOf("Seg", "Ter", "Qua", "Qui", "Sex", "Sáb", "Dom")
            "fr" -> listOf("Lu", "Ma", "Me", "Je", "Ve", "Sa", "Di")
            "it" -> listOf("Lu", "Ma", "Me", "Gi", "Ve", "Sa", "Do")
            "de" -> listOf("Mo", "Di", "Mi", "Do", "Fr", "Sa", "So")
            "zh" -> listOf("一", "二", "三", "四", "五", "六", "日")
            "ja" -> listOf("月", "火", "水", "木", "金", "土", "日")
            "ko" -> listOf("월", "화", "수", "목", "금", "토", "일")
            "ar" -> listOf("إث", "ثل", "أر", "خم", "جم", "سب", "أح")
            else -> listOf("Lu", "Ma", "Mi", "Ju", "Vi", "Sá", "Do")
        }
    }

